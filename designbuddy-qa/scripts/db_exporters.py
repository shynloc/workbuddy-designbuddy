def source_report(ir):
    ps = provenance_summary(ir)
    lines = ["# Source Report · %s" % esc_md(v(ir["brand"]["name"])), "",
             "生成：DesignBuddy %s · build %s · Design System %s" % (DESIGNBUDDY_VERSION, build_id(ir), ir["metadata"]["system_version"]), "",
             "## 来源分布", "", "| source_type | 数量 |", "|---|---|"]
    lines += ["| %s | %d |" % (k, n) for k, n in sorted(ps["counts"].items())]
    lines += ["", "## AI 推断与生成的事实（需重点审核）", ""]
    gen = [(p, f) for p, f in iter_facts(ir) if f["source_type"] in ("INFERRED", "GENERATED")]
    lines += ["- `%s` = %s（%s，%s，review=%s）" % (p, esc_md(str(f["value"]))[:80], f["source_type"], f["confidence"], f["review"]) for p, f in gen] or ["- 无"]
    lines += ["", "## 冲突与裁决", ""]
    lines += ["- %s：候选 %s → %s" % (c["field"], ", ".join(x["value"] for x in c["candidates"]), c.get("resolution", "未裁决"))
              for c in ir.get("conflicts", [])] or ["- 无"]
    lines += ["", "## 无障碍例外（USER_OVERRIDE）", ""]
    lines += ["- %s：%s" % (o["pair"], esc_md(o["reason"])) for o in ir["design_system"]["accessibility"]["overrides"]] or ["- 无"]

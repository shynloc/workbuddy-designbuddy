# ---------------------------------------------------------------- skill

def frontmatter_values(ir):
    b = ir["brand"]
    name, zh, en = v(b["name"]), v(b["name_zh"]), v(b["name_en"])
    others = [x for x in (zh, en) if x != name]
    aliases = [a for a in v(b["aliases"]) if a != name and a not in others]
    names = "、".join(others + aliases)
    desc = ("当用户为 %s（也称：%s）创建、修改或审核 PPT、Word、Excel、PDF、网页、海报、社交媒体视觉或其他品牌物料时，"
            "使用本品牌设计系统。用户未提及该品牌且语境不明确时不要使用。") % (name, names or "无")
    return {
        "fm_display_name": yaml_str("%s 品牌设计系统" % name),
        "fm_display_name_en": yaml_str("%s Brand System" % en),
        "fm_description": yaml_str(desc),
        "fm_description_zh": yaml_str("%s 的品牌设计系统：颜色、字体、版式、图片风格、各类物料规范与品牌 QA。" % name),
        "fm_description_en": yaml_str("Brand design system for %s: colors, type, layout, imagery, media rules and brand QA." % en),
        "fm_author": yaml_str(ir["metadata"].get("author") or name),
    }


def critical_rules(ir):
    rs = [r for r in ir["rules"] if r["level"] in ("MUST", "NEVER")][:15]
    return "\n".join("- `%s` **%s** %s" % (r["id"], r["level"], esc_md(r["text_zh"])) for r in rs)


def export_skill(ir, out_root, asset_dir=None):
    """Write <out_root>/<skill-name>/ and return (skill_dir, manifest)."""
    bid = build_id(ir)
    name = skill_name(ir)
    sk = Path(out_root) / name
    mapping = dict(frontmatter_values(ir), skill_name=name, brand_name=esc_md(v(ir["brand"]["name"])),
                   aliases=esc_md("、".join(v(ir["brand"]["aliases"]))), skill_version=ir["version"]["skill"],
                   system_version=ir["metadata"]["system_version"], schema_version=SCHEMA_VERSION,
                   generated_by="DesignBuddy %s" % DESIGNBUDDY_VERSION, build_id=bid, critical_rules=critical_rules(ir))
    files = {"SKILL.md": render(load_template("brand-skill.SKILL.md.tmpl"), mapping)}
    for fn, text in references(ir).items():
        files["references/" + fn] = text
    for script in ("validate_contrast.py", "validate_brand.py", "selfcheck.py"):
        files["scripts/" + script] = load_template("brand-skill.%s.tmpl" % script)
    files["templates/tokens.json"] = dump_json(tokens_json(ir))
    files["templates/tokens.css"] = tokens_css(ir)
    files["templates/asset-manifest.json"] = dump_json(asset_manifest(ir))
    files["templates/font-manifest.json"] = dump_json(ir["fonts"])
    binary = {}
    for a in ir["assets"]:
        if a["include"] and asset_dir is not None:
            src = Path(asset_dir) / a["file"]
            if src.is_file():
                binary["templates/asset." + Path(a["file"]).name] = src.read_bytes()
    hashes = {}
    for rel, text in files.items():
        p = write_text(sk / rel, text)
        hashes[rel] = sha256_bytes(p.read_bytes())
    for rel, data in binary.items():
        p = sk / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)
        hashes[rel] = sha256_bytes(data)
    manifest = {"skill": name, "skill_version": ir["version"]["skill"], "system_version": ir["metadata"]["system_version"],
                "build_id": bid, "generated_by": "DesignBuddy %s" % DESIGNBUDDY_VERSION, "generated_at": now_iso(),
                "files": dict(sorted(hashes.items()))}
    write_json(sk / "templates" / "build-manifest.json", manifest)
    return sk, manifest


def asset_manifest(ir):
    return [{"filename": a["file"], "id": a["id"], "type": a["type"], "source": "user-provided", "owner": a["owner"],
             "license": a["license"], "redistribution_allowed": a["redistribution_allowed"], "included": a["include"],
             "notes": a.get("notes") or ("" if a["include"] else "未获再分发许可或许可未知，不随包分发")} for a in ir["assets"]]


# ---------------------------------------------------------------- portable

def design_md(ir):
    ds, b = ir["design_system"], ir["brand"]
    fams = families(ir)
    yaml_colors = "\n".join("  %s: \"%s\"" % (t.split(".", 1)[1], hx) for t, _r, _n, hx, _u in colors(ir))
    mapping = {
        "fm_name": yaml_str(v(b["name"])), "system_version": ir["metadata"]["system_version"],
        "generated_by": "DesignBuddy %s" % DESIGNBUDDY_VERSION, "schema_version": SCHEMA_VERSION,
        "yaml_colors": yaml_colors, "yaml_heading": yaml_str(v(fams["heading"]["family"])),
        "yaml_body": yaml_str(v(fams["body"]["family"])), "heading_weight": v(ds["typography"]["heading_weight"]),
        "spacing_base": ds["spacing"]["base"], "yaml_radius": yaml_str(v(ds["radius"])),
        "brand_name": esc_md(v(b["name"])), "positioning": esc_md(v(b["positioning"])),
        "personality": esc_md("、".join(v(b["personality"]))), "direction_name": esc_md(ds["direction"]["name_zh"]),
        "color_rows": "\n".join("| `%s` | %s | `%s` | %s |" % (t, esc_md(n), hx, esc_md(u)) for t, _r, n, hx, u in colors(ir)),
        "type_rows": "\n".join("| %s | %s | %s |" % (r, esc_md(v(f["family"])), esc_md(", ".join(f["fallbacks"]))) for r, f in fams.items()),
        "type_scale": ", ".join("%s %d" % (s["token"], s["size_px"]) for s in ds["typography"]["scale"]),
        "spacing_scale": ", ".join(str(ds["spacing"]["base"] * n) for n in SPACE_STEPS), "radius": esc_md(v(ds["radius"])),
        "grid": esc_md(ds["grid"]["web"]), "imagery": esc_md(v(ds["imagery"])), "iconography": esc_md(v(ds["iconography"])),
        "motion": esc_md(v(ds["motion"])), "voice": esc_md(v(b["voice"]["tone"])), "rules": _rules_md(ir),
    }
    return render(load_template("portable.DESIGN.md.tmpl"), mapping)


def export_portable(ir, out_dir, asset_dir=None, preview_dir=None):
    out = Path(out_dir)
    bid = build_id(ir)
    write_text(out / "DESIGN.md", design_md(ir))
    write_json(out / "brand-ir.json", stable_ir(ir))
    write_json(out / "tokens.json", tokens_json(ir))
    write_text(out / "tokens.css", tokens_css(ir))
    write_json(out / "asset-manifest.json", asset_manifest(ir))
    write_json(out / "font-manifest.json", ir["fonts"])
    write_text(out / "README.md", render(load_template("portable.README.md.tmpl"), {
        "brand_name": esc_md(v(ir["brand"]["name"])), "generated_by": "DesignBuddy %s" % DESIGNBUDDY_VERSION,
        "system_version": ir["metadata"]["system_version"], "build_id": bid, "schema_version": SCHEMA_VERSION}))
    for a in ir["assets"]:
        if a["include"] and asset_dir is not None and (Path(asset_dir) / a["file"]).is_file():
            p = out / "assets" / Path(a["file"]).name
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_bytes((Path(asset_dir) / a["file"]).read_bytes())
    if preview_dir:
        for f in sorted(Path(preview_dir).glob("*.html")):
            write_text(out / "examples" / f.name, f.read_text(encoding="utf-8"))
    return out


# ---------------------------------------------------------------- preview

def export_preview(ir, out_dir):
    b, ds = ir["brand"], ir["design_system"]
    name = v(b["name"])
    css = tokens_css(ir)
    common = {"brand_name": esc_html(name), "generated_by": "DesignBuddy %s" % DESIGNBUDDY_VERSION, "build_id": build_id(ir),
              "tokens_css": css, "system_version": ir["metadata"]["system_version"],
              "direction_name": esc_html(ds["direction"]["name_zh"])}
    poster = render(load_template("preview.poster.html.tmpl"), dict(common, headline=esc_html(name),
                    lead=esc_html(v(b["positioning"])), subline=esc_html("面向%s。" % v(b["audience"])),
                    cta=esc_html("了解 %s" % name)))
    cards_data = [("品牌性格", "、".join(v(b["personality"])) or "—"), ("语气", v(b["voice"]["tone"])),
                  ("视觉方向", "%s · %s" % (ds["direction"]["name_zh"], v(ds["layout"])))]
    cards = "\n".join('    <div class="card"><b>%s</b>%s</div>' % (esc_html(t), esc_html(x)) for t, x in cards_data)
    sw = "\n".join('    <div class="sw"><i style="background:%s"></i><span>%s<br>%s</span></div>' % (hx, esc_html(n), hx)
                   for _t, _r, n, hx, _u in colors(ir))
    onepager = render(load_template("preview.onepager.html.tmpl"), dict(common, headline=esc_html(v(b["positioning"])),
                      subline=esc_html("为%s设计。" % v(b["audience"])), principle_cards=cards, swatches=sw))
    out = Path(out_dir)
    write_text(out / "poster.html", poster)
    write_text(out / "onepager.html", onepager)
    return [out / "poster.html", out / "onepager.html"]



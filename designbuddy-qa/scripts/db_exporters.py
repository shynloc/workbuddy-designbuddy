"""Exporters: Brand IR -> tokens, Brand Skill, Portable bundle, Preview, Source report.

Every output value comes from the IR. Templates live in templates/ and are
rendered with escaped values; nothing is written outside the given out_dir.
"""
import copy
from pathlib import Path

from db_ir import contrast_table, iter_facts
from db_engine import provenance_summary
from db_util import (DBError, DESIGNBUDDY_VERSION, SCHEMA_VERSION, canonical, dump_json, esc_html,
                   esc_md, load_template, render, sha256_bytes, write_json, write_text, yaml_str, now_iso)

SPACE_STEPS = (1, 2, 3, 4, 6, 8, 12, 16)
VOLATILE_META = ("created_at", "preview")


def v(f):
    return f["value"] if isinstance(f, dict) and "value" in f else f


def stable_ir(ir):
    data = copy.deepcopy(ir)
    for k in VOLATILE_META:
        data.get("metadata", {}).pop(k, None)
    return data


def build_id(ir):
    return sha256_bytes((canonical(stable_ir(ir)) + DESIGNBUDDY_VERSION).encode("utf-8"))[:12]


def skill_name(ir):
    return "%s-brand-system" % ir["brand"]["slug"]


def colors(ir):
    return [(c["token"], c["role"], c["name"], v(c["hex"]), c["usage"]) for c in ir["design_system"]["colors"]]


def families(ir):
    return {f["role"]: f for f in ir["design_system"]["typography"]["families"]}


def font_stack(f):
    names = [v(f["family"])] + f["fallbacks"]
    return ", ".join(n if n in ("sans-serif", "serif", "monospace") else "'%s'" % n.replace("'", "") for n in names)


# ---------------------------------------------------------------- tokens

def tokens_json(ir):
    ds = ir["design_system"]
    fams = families(ir)
    overrides = {o["pair"] for o in ds["accessibility"]["overrides"]}
    out = {
        "$description": "%s design tokens (W3C DTCG). Generated by DesignBuddy %s from Brand IR %s."
                        % (v(ir["brand"]["name"]), DESIGNBUDDY_VERSION, ir["metadata"]["system_version"]),
        "color": {t.split(".", 1)[1]: {"$value": hx, "$type": "color", "$description": "%s — %s" % (n, u)}
                  for t, _r, n, hx, u in colors(ir)},
        "font": {r: {"$value": v(f["family"]), "$type": "fontFamily"} for r, f in fams.items()},
        "fontWeight": {"heading": {"$value": v(ds["typography"]["heading_weight"]), "$type": "fontWeight"},
                       "body": {"$value": ds["typography"]["body_weight"], "$type": "fontWeight"}},
        "fontSize": {s["token"]: {"$value": "%dpx" % s["size_px"], "$type": "dimension"} for s in ds["typography"]["scale"]},
        "space": {str(n): {"$value": "%dpx" % (ds["spacing"]["base"] * n), "$type": "dimension"} for n in SPACE_STEPS},
        "radius": {"base": {"$value": v(ds["radius"]), "$type": "dimension"}},
        "$extensions": {"designbuddy.contrastPairs": [
            {"name": p["name"], "fg": p["fg"], "bg": p["bg"], "kind": p.get("kind", "text"), "override": p["name"] in overrides}
            for p in ds["accessibility"]["pairs"]]},
    }
    return out


def tokens_css(ir):
    ds = ir["design_system"]
    fams = families(ir)
    lines = [":root {"]
    for t, _r, _n, hx, _u in colors(ir):
        lines.append("  --%s: %s;" % (t.replace(".", "-"), hx))
    lines.append("  --font-heading: %s;" % font_stack(fams["heading"]))
    lines.append("  --font-body: %s;" % font_stack(fams["body"]))
    lines.append("  --heading-weight: %s;" % v(ds["typography"]["heading_weight"]))
    for s in ds["typography"]["scale"]:
        lines.append("  --type-%s: %dpx;" % (s["token"], s["size_px"]))
    for n in SPACE_STEPS:
        lines.append("  --space-%d: %dpx;" % (n, ds["spacing"]["base"] * n))
    lines.append("  --radius: %s;" % v(ds["radius"]))
    lines.append("  --shadow-sm: %s;" % ds["shadows"]["sm"])
    lines.append("  --shadow-md: %s;" % ds["shadows"]["md"])
    lines.append("}")
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- references

def _rules_md(ir, levels=None):
    rows = []
    for r in ir["rules"]:
        if levels and r["level"] not in levels:
            continue
        rows.append("- `%s` **%s** %s" % (r["id"], r["level"], esc_md(r["text_zh"])))
    return "\n".join(rows) or "- （无）"


